data class DirectionPath(
    val title: String,
    val category: String,
    val summary: String,
    val difficulty: String, // Moderate, High, Rigorous
    val estimatedTimeMonths: Int,
    val financialCost: String,
    val upside: String,
    val downsideRisk: String,
    val requiredSkills: List<String>,
    val firstAction: String
)

@Composable
fun ImLostScreen(
    onAdoptGoal: (title: String, desc: String, category: String, firstAction: String) -> Unit,
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    BackHandler { onBack() }
    val scrollState = rememberScrollState()

    var whatToImprove by remember { mutableStateOf("Career velocity and practical engineering capability") }
    var whatEnjoy by remember { mutableStateOf("Building real tools, coding, problem solving") }
    var whatDislike by remember { mutableStateOf("Passive lectures, memorization, repetitive admin") }
    var hoursAvailable by remember { mutableStateOf("3") }
    var successDefinition by remember { mutableStateOf("High-impact role, autonomy, solid income") }

    var pathsGenerated by remember { mutableStateOf(false) }

    val generatedPaths = remember(whatToImprove, whatEnjoy, hoursAvailable) {
        listOf(
            DirectionPath(
                title = "Path A: High-Leverage Software & AI Systems Engineer",
                category = "Career",
                summary = "Build production-grade mobile and AI applications with verifiable open-source repositories.",
                difficulty = "Moderate to High",
                estimatedTimeMonths = 6,
                financialCost = "₹0 (Open-source tools & free tiers)",
                upside = "High market demand, remote flexibility, scalable compensation",
                downsideRisk = "Requires rigorous personal consistency; steep learning curve on architecture",
                requiredSkills = listOf("Kotlin/Android", "REST APIs", "Git", "System Design"),
                firstAction = "Build a single offline-first notes engine and publish repository on GitHub"
            ),
            DirectionPath(
                title = "Path B: Independent Product & Micro-SaaS Builder",
                category = "Business",
                summary = "Identify underserved micro-niches, build focused MVPs, and validate with 5 paying clients.",
                difficulty = "High",
                estimatedTimeMonths = 9,
                financialCost = "Minimal (Domain + Cloud hosting < ₹1,000/mo)",
                upside = "Direct ownership of equity, recurring revenue, creative control",
                downsideRisk = "Customer discovery takes patience; distribution is challenging",
                requiredSkills = listOf("Full-Stack Prototyping", "Customer Interviews", "Unit Economics"),
                firstAction = "Conduct 5 interviews with target professionals about their most annoying manual workflow"
            ),
            DirectionPath(
                title = "Path C: Applied Research & Deep Technical Specialization",
                category = "Education",
                summary = "Master algorithmic fundamentals, benchmarks, and research implementations targeting elite labs or higher degrees.",
                difficulty = "Rigorous",
                estimatedTimeMonths = 12,
                financialCost = "Low to Medium (Exam fees or lab tuition)",
                upside = "Deep intellectual moat, academic credibility, access to frontier labs",
                downsideRisk = "Long gestation period before commercial payoff; heavy theoretical requirements",
                requiredSkills = listOf("Linear Algebra", "ML Benchmarking", "Paper Implementation"),
                firstAction = "Implement a classic benchmark paper from scratch and replicate its accuracy"
            )
        )
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.background)
            .verticalScroll(scrollState)
            .padding(horizontal = 20.dp, vertical = 14.dp)
            .testTag("im_lost_screen"),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        // Top Bar
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            IconButton(
                onClick = onBack,
                modifier = Modifier.testTag("im_lost_back_button")
            ) {
                Icon(
                    imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                    contentDescription = "Back",
                    tint = MaterialTheme.colorScheme.onSurface
                )
            }
            Spacer(modifier = Modifier.width(8.dp))
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = "Direction Finder: \"I'm Lost\"",
                    style = MaterialTheme.typography.titleLarge.copy(fontWeight = FontWeight.Bold),
                    color = MaterialTheme.colorScheme.onSurface
                )
                Text(
                    text = "Calibrate when you feel uncertain about where to dedicate your energy",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
        }

        // Intake Form Card
        Card(
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
            border = BorderStroke(1.dp, MaterialTheme.colorScheme.outline.copy(alpha = 0.25f)),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                Text(
                    text = "CALIBRATION QUESTIONNAIRE",
                    style = MaterialTheme.typography.labelSmall.copy(fontWeight = FontWeight.ExtraBold, letterSpacing = 1.sp),
                    color = AmberGoldPrimary
                )

                OutlinedTextField(
                    value = whatToImprove,
                    onValueChange = { whatToImprove = it },
                    label = { Text("What area of life do you most want to improve?") },
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp)
                )

                OutlinedTextField(
                    value = whatEnjoy,
                    onValueChange = { whatEnjoy = it },
                    label = { Text("What activities bring you genuine energy or flow?") },
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp)
                )

                OutlinedTextField(
                    value = whatDislike,
                    onValueChange = { whatDislike = it },
                    label = { Text("What tasks drain your energy or feel useless?") },
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp)
                )

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    OutlinedTextField(
                        value = hoursAvailable,
                        onValueChange = { hoursAvailable = it },
                        label = { Text("Hours / Day") },
                        modifier = Modifier.weight(1f),
                        shape = RoundedCornerShape(10.dp)
                    )
                    OutlinedTextField(
                        value = successDefinition,
                        onValueChange = { successDefinition = it },
                        label = { Text("Definition of Success") },
                        modifier = Modifier.weight(2f),
                        shape = RoundedCornerShape(10.dp)
                    )
                }

                Button(
                    onClick = { pathsGenerated = true },
                    shape = RoundedCornerShape(10.dp),
                    colors = ButtonDefaults.buttonColors(containerColor = AmberGoldPrimary, contentColor = Color(0xFF0F172A)),
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(top = 6.dp)
                        .testTag("generate_paths_button")
                ) {
                    Icon(Icons.Default.Explore, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(if (pathsGenerated) "Regenerate Strategic Paths" else "Generate 3 Concrete Paths", fontWeight = FontWeight.Bold)
                }
            }
        }

        // Generated Paths Section
        if (pathsGenerated) {
            Text(
                text = "COMPARATIVE STRATEGIC PATHS",
                style = MaterialTheme.typography.labelSmall.copy(fontWeight = FontWeight.ExtraBold, letterSpacing = 1.2.sp),
                color = SkySecondary
            )

            generatedPaths.forEach { path ->
                Card(
                    shape = RoundedCornerShape(16.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                    border = BorderStroke(1.dp, MaterialTheme.colorScheme.outline.copy(alpha = 0.25f)),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Column(
                        modifier = Modifier.padding(16.dp),
                        verticalArrangement = Arrangement.spacedBy(10.dp)
                    ) {
                        Text(
                            text = path.title,
                            style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold),
                            color = MaterialTheme.colorScheme.onSurface
                        )

                        Text(
                            text = path.summary,
                            style = MaterialTheme.typography.bodyMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )

                        // Metric Matrix
                        Column(
                            verticalArrangement = Arrangement.spacedBy(4.dp),
                            modifier = Modifier
                                .fillMaxWidth()
                                .background(MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.4f), RoundedCornerShape(8.dp))
                                .padding(10.dp)
                        ) {
                            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                                Text("Difficulty & Time:", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Text("${path.difficulty} (~${path.estimatedTimeMonths} months)", style = MaterialTheme.typography.bodySmall.copy(fontWeight = FontWeight.Bold), color = MaterialTheme.colorScheme.onSurface)
                            }
                            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                                Text("Capital Required:", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Text(path.financialCost, style = MaterialTheme.typography.bodySmall.copy(fontWeight = FontWeight.Bold), color = MaterialTheme.colorScheme.onSurface)
                            }
                            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                                Text("Primary Upside:", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Text(path.upside, style = MaterialTheme.typography.bodySmall.copy(fontWeight = FontWeight.Bold), color = EmeraldTertiary)
                            }
                            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                                Text("Downside Risk:", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Text(path.downsideRisk, style = MaterialTheme.typography.bodySmall.copy(fontWeight = FontWeight.Bold), color = PriorityP1)
                            }
                        }

                        // Immediate First Step
                        Surface(
                            shape = RoundedCornerShape(8.dp),
                            color = AmberGoldPrimary.copy(alpha = 0.12f),
                            modifier = Modifier.fillMaxWidth()
                        ) {
                            Column(modifier = Modifier.padding(10.dp)) {
                                Text(
                                    text = "IMMEDIATE FIRST ACTION",
                                    style = MaterialTheme.typography.labelSmall.copy(fontWeight = FontWeight.ExtraBold),
                                    color = AmberGoldPrimary
                                )
                                Text(
                                    text = path.firstAction,
                                    style = MaterialTheme.typography.bodySmall.copy(fontWeight = FontWeight.Medium),
                                    color = MaterialTheme.colorScheme.onSurface
                                )
                            }
                        }

                        Button(
                            onClick = {
                                onAdoptGoal(path.title, path.summary, path.category, path.firstAction)
                            },
                            shape = RoundedCornerShape(10.dp),
                            colors = ButtonDefaults.buttonColors(containerColor = MaterialTheme.colorScheme.surfaceVariant, contentColor = MaterialTheme.colorScheme.onSurface),
                            modifier = Modifier.fillMaxWidth()
                        ) {
                            Icon(Icons.Default.CheckCircle, contentDescription = null, modifier = Modifier.size(16.dp), tint = EmeraldTertiary)
                            Spacer(modifier = Modifier.width(6.dp))
                            Text("Adopt as Active Goal", fontWeight = FontWeight.Bold)
                        }
                    }
                }
            }
        }

        Spacer(modifier = Modifier.height(40.dp))
    }
}
